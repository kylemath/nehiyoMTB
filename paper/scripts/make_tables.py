"""Tables and headline numbers generated from docs/catalogue.json and the
Supabase migrations.

generated/signs_table.tex   one row per finished sign: number, English name,
                            SRO, syllabics, literal sense, filament colours
                            (as swatches, bottom layer first), print method and
                            the page's review status.
generated/schema_table.tex  the tables the companion app's backend keeps.
generated/catalogue.tex     counts quoted in the prose.
"""
from __future__ import annotations

import re
from collections import Counter

from matplotlib.colors import to_hex

from common import GEN, REPO, is_built, models, tex_escape, write_macros

STATUS = {"published": "published", "user-reviewed": "reviewed",
          "agent-drafted": "machine draft", "draft": "draft"}


def gloss(m: dict) -> str:
    """A short literal sense pulled from the page's linguistics.meaning field."""
    ling = (m.get("pageContent") or {}).get("linguistics") or {}
    mean = (ling.get("meaning") or "").strip()
    q = r"[‘'“\"](.+?)[’'”\"](?=[\s,;.)]|$)"
    mm = re.search(r"literally\s+" + q, mean)
    if mm:
        return mm.group(1)
    left, _, right = mean.partition(" — ")
    if left and left.lower() != m["englishName"].lower().replace("'", "’") and left.lower() != m["englishName"].lower():
        return left
    mm = re.search(q, right)
    return mm.group(1) if mm else ""


def swatches(colors: list[str]) -> str:
    out = []
    for c in colors:
        try:
            h = to_hex(c)[1:].upper()
        except ValueError:
            continue
        out.append(r"\swatch{" + h + "}")
    return "".join(out)


def main():
    ms = models()
    built = sorted([m for m in ms if is_built(m)], key=lambda m: m["signNumber"])
    rows = []
    for m in built:
        method = "tonal" if m.get("printEffect") else "layer swap"
        rows.append(" & ".join([
            str(m["signNumber"]),
            tex_escape(m["englishName"]),
            r"\textit{" + tex_escape(m["creeName"]) + "}",
            m["creeSyllabics"] or "--",
            tex_escape(gloss(m)) or "--",
            swatches(m.get("colors") or []),
            method + r"\newline \textcolor{gray}{" +
            STATUS.get((m.get("pageContent") or {}).get("pageStatus"), "--") + "}",
        ]) + r" \\")
    body = "\n".join(rows)
    (GEN / "signs_table.tex").write_text(
        "% generated by paper/scripts/make_tables.py\n"
        r"\begin{tabularx}{\textwidth}{@{}r>{\raggedright\arraybackslash}p{1.45cm}"
        r">{\raggedright\arraybackslash}p{2.35cm}>{\raggedright\arraybackslash}p{2.45cm}"
        r">{\raggedright\arraybackslash}X>{\raggedright\arraybackslash}p{1.55cm}"
        r">{\raggedright\arraybackslash}p{1.35cm}@{}}" "\n"
        r"\toprule" "\n"
        r"\textbf{No.} & \textbf{English} & \textbf{SRO} & \textbf{Syllabics} & "
        r"\textbf{Literal sense} & \textbf{Colours} & \textbf{Print, page} \\" "\n"
        r"\midrule" "\n" + body + "\n" r"\bottomrule" "\n" r"\end{tabularx}" "\n",
        encoding="utf-8")

    # ---------------------------------------------------------- backend schema
    tables = []
    for f in sorted((REPO / "supabase" / "migrations").glob("*.sql")):
        sql = f.read_text(encoding="utf-8")
        for mt in re.finditer(r"create table public\.(\w+)\s*\((.*?)\n\);", sql, re.S | re.I):
            name, cols = mt.group(1), mt.group(2)
            ncols = sum(1 for l in cols.splitlines()
                        if re.match(r"\s+[a-z_]+\s+[a-z]", l) and not re.match(r"\s+(primary|unique|constraint|check|foreign)", l, re.I))
            rls = bool(re.search(rf"alter table public\.{name}\s+enable row level security", sql, re.I))
            tables.append((name, ncols, f.name, rls))
    lines = ["% generated by paper/scripts/make_tables.py", r"\begin{tabular}{@{}lrll@{}}", r"\toprule",
             r"\textbf{Table} & \textbf{Columns} & \textbf{Migration} & \textbf{Row-level security} \\", r"\midrule"]
    for n, c, f, r in tables:
        lines.append(f"\\texttt{{{tex_escape(n)}}} & {c} & \\texttt{{{tex_escape(f)}}} & {'yes' if r else 'no'} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (GEN / "schema_table.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    status = Counter((m.get("pageContent") or {}).get("pageStatus") for m in ms)
    tonal = sum(1 for m in built if m.get("printEffect"))
    ncols = [len(m.get("colors") or []) for m in built]
    write_macros("catalogue", {
        "catModels": len(ms),
        "catBuilt": len(built),
        "catDrafts": len(ms) - len(built),
        "catPublished": status.get("published", 0),
        "catReviewed": status.get("user-reviewed", 0),
        "catAgentDrafted": status.get("agent-drafted", 0),
        "catDraftStatus": status.get("draft", 0),
        "catTonal": tonal,
        "catLayerSwap": len(built) - tonal,
        "catMinColours": min(ncols),
        "catMaxColours": max(ncols),
        "catFlaggedReview": sum(1 for m in ms if any(
            re.search(r"elder|fluent speaker|speaker review|human review", n, re.I)
            for n in (m.get("pageContent") or {}).get("notes", []) or [])),
        "dbTables": len(tables),
        "dbRls": sum(1 for t in tables if t[3]),
    })
    print("tables:", len(built), "built;", status, tables)


if __name__ == "__main__":
    main()
