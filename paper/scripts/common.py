def catalogue() -> dict:
    return json.loads((DOCS / "catalogue.json").read_text(encoding="utf-8"))


def models() -> list[dict]:
    return catalogue()["models"]


def is_built(m: dict) -> bool:
    """A sign that exists as a finished physical plaque (STL + photo + store
    listing), as opposed to a generated draft for a trail that has no sign yet."""
    return bool(m.get("shopify")) and m.get("status") == "published"


def workbench() -> list[dict]:
    """The DATA array of the Translation Workbench (docs/cree-trail-names.html):
    one entry per Edmonton trail with three candidate Cree names each."""
    html = (DOCS / "cree-trail-names.html").read_text(encoding="utf-8")
    i = html.index("const DATA = [")
    j = html.index("\n];", i)
    js = html[i + len("const DATA = "): j + 2]
    # Prefer node (exact JS semantics); fall back to a JSON-ish conversion.
    try:
        out = subprocess.run(["node", "-e", f"process.stdout.write(JSON.stringify({js}))"],
                             capture_output=True, text=True, check=True)
        return json.loads(out.stdout)
    except Exception:
        s = re.sub(r'([{,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:', r'\1"\2":', js)
        s = re.sub(r',\s*([}\]])', r'\1', s)
        return json.loads(s)


def drafts_manifest() -> dict:
    return json.loads((DOCS / "sign-drafts" / "manifest.json").read_text(encoding="utf-8"))


def git_log() -> list[tuple[str, str, str]]:
    """(iso date, author, subject) oldest first."""
    out = subprocess.run(["git", "-C", str(REPO), "log", "--reverse",
                          "--format=%ad%x1f%an%x1f%s", "--date=short"],
                         capture_output=True, text=True, check=True).stdout
    return [tuple(l.split("\x1f")) for l in out.splitlines() if l.strip()]


def tex_escape(s: str) -> str:
    rep = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}"}
    return "".join(rep.get(c, c) for c in s)


def write_macros(name: str, values: dict):
    """Write \\newcommand macros so numbers quoted in the prose come from data."""
    lines = [f"% generated by paper/scripts/{name}.py — do not edit"]
    for k, v in values.items():
        lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    (GEN / f"{name}.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
